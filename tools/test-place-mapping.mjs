import {readFileSync} from "node:fs";
import vm from "node:vm";
import assert from "node:assert/strict";
const bundle = readFileSync(new URL("../assets/index-BpU9kvz8.js",import.meta.url),"utf8");
const pure = bundle.slice(bundle.indexOf("function gwbPlaceKey"),bundle.indexOf("function gwbEnsurePlaceMapping"));
const api = vm.runInNewContext(pure+";({gwbResolvePlaceMapping,gwbValidAssignment,gwbMappingSignature})");
const resolve = (entry, template) => JSON.parse(JSON.stringify(api.gwbResolvePlaceMapping(entry,template)));
const field = (page,x=0) => ({page,x,y:0,w:40,h:40,pdfOrder:0});
const label = (text,x=2) => ({text,x,y:2,w:20,h:5});
const entry = {order:"1",itemId:"1",places:["лицо","оборот"],placeCount:2,placeCountReliable:true};
const template = {fieldOptions:[field(0,50),field(0)],metadataByPage:[{placeLabels:[label("лицо"),label("оборот",52)]}]};
assert.deepEqual(resolve(entry,template).byField,[1,0]);
assert.equal(resolve(entry,template).source,"pdf-label-geometry");
assert.equal(resolve(entry,{...template,metadataByPage:[]}).status,"manual");
assert.equal(resolve({...entry,placeCountReliable:false},template).status,"manual");
assert.equal(resolve({...entry,places:["лицо","лицо"]},template).status,"manual");
assert.equal(resolve({...entry,places:[],placeCount:0},template).status,"error");
assert.equal(resolve(entry,{...template,fieldOptions:[field(0)]}).status,"error");
assert.equal(resolve(entry,{...template,fieldOptions:[field(0),field(0,50),field(1)]}).status,"error");
assert.equal(resolve({...entry,places:["лицо"],placeCount:1},{fieldOptions:[field(0)]}).source,"single");
assert.equal(resolve({...entry,places:["лицо"],placeCount:1,placeCountReliable:false},{fieldOptions:[field(0)]}).status,"manual");
assert.equal(resolve(entry,{...template,metadataByPage:[{placeLabels:[label("оборот"),label("лицо"),label("лицо",52)]}]}).status,"manual");
assert.equal(resolve(entry,{...template,metadataByPage:[{placeLabels:[{...label("лицо"),x:43},label("оборот",52)]}]}).status,"manual");
assert.deepEqual(resolve(entry,{fieldOptions:[field(0),field(1)],metadataByPage:[{placeLabels:[label("оборот [print2]")]},{placeLabels:[label("лицо [print1]")]}]}).byField,[1,0]);
assert.equal(api.gwbValidAssignment([0,0],2),false);
assert.equal(api.gwbValidAssignment([-1,1],2),false);
assert.equal(api.gwbValidAssignment([0,2],2),false);
assert.equal(api.gwbValidAssignment([1,0],2),true);
assert.notEqual(api.gwbMappingSignature(entry,template),api.gwbMappingSignature({...entry,itemId:"2"},template));
assert.notEqual(api.gwbMappingSignature(entry,template),api.gwbMappingSignature(entry,{...template,fieldOptions:[field(0,55),field(0)]}));
console.log("Order place mapping: 18 assertions passed");
